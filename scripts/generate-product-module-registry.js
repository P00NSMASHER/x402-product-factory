"use strict";

const fs=require("node:fs");
const path=require("node:path");
const registry=require("../product-registry.json");

const ROOT=path.resolve(__dirname,"..");
const OUT=path.join(ROOT,"generated","product-modules.js");

function moduleDirectory(product){
  const directory=product.module_directory??product.id;
  if(typeof directory!=="string"||!/^[a-z0-9][a-z0-9-]*$/.test(directory)){
    throw new Error(product.id+": invalid module_directory");
  }
  return directory;
}

function has(directory,file){
  return fs.existsSync(path.join(ROOT,"products",directory,file));
}

function buildSource(){
  const metadata=[];
  const services=[];
  const handlers=[];

  for(const product of registry.products){
    const id=product.id;
    const directory=moduleDirectory(product);
    const base="../products/"+directory+"/";
    if(has(directory,"metadata.js")) metadata.push(`  ${JSON.stringify(id)}:require(${JSON.stringify(base+"metadata")})`);
    if(has(directory,"service.js")) services.push(`  ${JSON.stringify(id)}:require(${JSON.stringify(base+"service")})`);
    if(has(directory,"paid-handler.js")) handlers.push(`  ${JSON.stringify(id)}:require(${JSON.stringify(base+"paid-handler")})`);
  }

  return [
    '"use strict";',
    '',
    '// Generated by scripts/generate-product-module-registry.js.',
    '// Do not hand-edit. This file contains only static local requires so it can be bundled for AppDeploy.',
    '',
    'const METADATA_MODULES=Object.freeze({',
    metadata.join(',\n'),
    '});',
    '',
    'const SERVICE_MODULES=Object.freeze({',
    services.join(',\n'),
    '});',
    '',
    'const PAID_HANDLER_MODULES=Object.freeze({',
    handlers.join(',\n'),
    '});',
    '',
    'module.exports={METADATA_MODULES,SERVICE_MODULES,PAID_HANDLER_MODULES};',
    ''
  ].join('\n');
}

function write(){
  const source=buildSource();
  fs.mkdirSync(path.dirname(OUT),{recursive:true});
  fs.writeFileSync(OUT,source,"utf8");
  return source;
}

function check(){
  const expected=buildSource();
  const actual=fs.existsSync(OUT)?fs.readFileSync(OUT,"utf8"):"";
  if(actual!==expected){
    const error=new Error("generated product module registry is stale; run node scripts/generate-product-module-registry.js");
    error.code="GENERATED_REGISTRY_STALE";
    throw error;
  }
  return expected;
}

function main(){
  const mode=process.argv.includes("--check")?"check":"write";
  const source=mode==="check"?check():write();
  console.log(JSON.stringify({ok:true,mode,output:path.relative(path.resolve(__dirname,".."),OUT).replaceAll("\\","/"),bytes:Buffer.byteLength(source)},null,2));
}

if(require.main===module)main();

module.exports={ROOT,OUT,moduleDirectory,buildSource,write,check};
