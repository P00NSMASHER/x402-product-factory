"use strict";

const fs=require("node:fs");
const path=require("node:path");

const ROOT=path.resolve(__dirname,"..");
const SPEC_DIR=path.join(ROOT,"specs");
const OUT=path.join(ROOT,"generated","spec-runtime-bindings.js");

function discoverSpecFiles(){
  return fs.readdirSync(SPEC_DIR)
    .filter(name=>/^\d{3}-.+\.json$/.test(name))
    .sort();
}

function loadSpecs(){
  return discoverSpecFiles().map(name=>
    JSON.parse(fs.readFileSync(path.join(SPEC_DIR,name),"utf8"))
  );
}

function requirePath(modulePath){
  if(typeof modulePath!=="string"||!modulePath.endsWith(".js")){
    throw new TypeError("implementation service_module must end in .js");
  }
  return "../"+modulePath.slice(0,-3);
}

function render(specs=loadSpecs()){
  const moduleLines=specs.map(spec=>
    "  "+JSON.stringify(spec.id)+":require("+JSON.stringify(requirePath(spec.implementation.service_module))+")"
  );
  const bindings=Object.fromEntries(specs.map(spec=>[
    spec.id,
    {
      service_module:spec.implementation.service_module,
      service_factory_export:spec.implementation.service_factory_export,
      validator_export:spec.implementation.validator_export,
      paid_handler_template:spec.implementation.paid_handler_template
    }
  ]));

  return [
    '"use strict";',
    '',
    '// Generated by scripts/generate-spec-runtime-bindings.js. Do not hand-edit.',
    'const {createStandardPaidHandler}=require("../packages/x402/standard-paid-handler");',
    'const {PRODUCTS}=require("./spec-metadata");',
    '',
    'const SERVICE_MODULES=Object.freeze({',
    moduleLines.join(",\n"),
    '});',
    '',
    'const BINDINGS=Object.freeze('+JSON.stringify(bindings,null,2)+');',
    '',
    'function binding(productId){',
    '  const value=BINDINGS[productId];',
    '  if(!value)throw new Error("unknown spec product: "+productId);',
    '  return value;',
    '}',
    '',
    'function serviceModule(productId){',
    '  const value=SERVICE_MODULES[productId];',
    '  if(!value)throw new Error("service module missing for "+productId);',
    '  return value;',
    '}',
    '',
    'function serviceFactory(productId){',
    '  const item=binding(productId);',
    '  const factory=serviceModule(productId)[item.service_factory_export];',
    '  if(typeof factory!=="function")throw new Error(productId+" service factory missing: "+item.service_factory_export);',
    '  return factory;',
    '}',
    '',
    'function validator(productId){',
    '  const item=binding(productId);',
    '  const validate=serviceModule(productId)[item.validator_export];',
    '  if(typeof validate!=="function")throw new Error(productId+" validator missing: "+item.validator_export);',
    '  return validate;',
    '}',
    '',
    'function createService(productId,args){',
    '  return serviceFactory(productId)(args);',
    '}',
    '',
    'function createPaidHandler(productId,args){',
    '  const product=PRODUCTS[productId];',
    '  if(!product)throw new Error("generated metadata missing for "+productId);',
    '  if(binding(productId).paid_handler_template!=="standard_get_v1"){',
    '    throw new Error("unsupported paid handler template for "+productId);',
    '  }',
    '  return createStandardPaidHandler({...args,product,validateInput:validator(productId)});',
    '}',
    '',
    'module.exports={',
    '  SERVICE_MODULES,',
    '  BINDINGS,',
    '  binding,',
    '  serviceModule,',
    '  serviceFactory,',
    '  validator,',
    '  createService,',
    '  createPaidHandler',
    '};',
    ''
  ].join("\n");
}

function write(){
  const content=render();
  fs.mkdirSync(path.dirname(OUT),{recursive:true});
  fs.writeFileSync(OUT,content,"utf8");
  return content;
}

function check(){
  const expected=render();
  const actual=fs.existsSync(OUT)?fs.readFileSync(OUT,"utf8"):"";
  if(actual!==expected){
    const error=new Error("generated spec runtime bindings are stale; run node scripts/generate-spec-runtime-bindings.js");
    error.code="GENERATED_SPEC_RUNTIME_BINDINGS_STALE";
    throw error;
  }
  return expected;
}

function main(){
  const mode=process.argv.includes("--check")?"check":"write";
  const content=mode==="check"?check():write();
  console.log(JSON.stringify({
    ok:true,
    mode,
    products:loadSpecs().length,
    bytes:Buffer.byteLength(content)
  },null,2));
}

if(require.main===module)main();

module.exports={ROOT,SPEC_DIR,OUT,discoverSpecFiles,loadSpecs,requirePath,render,write,check};
