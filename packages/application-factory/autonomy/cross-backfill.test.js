'use strict';
const test=require('node:test'),assert=require('node:assert/strict');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path'),crypto=require('node:crypto');
const {runCrossCycle,planCrossCycle,readJournal}=require('./cross-cycle');
const {loadOpportunities}=require('./cross-family');
const {planCrossBackfill,runCrossBackfill}=require('./cross-backfill');
const {main}=require('../../../scripts/backfill-cross-family');
const EPOCH=Date.parse('2026-10-13T00:00:00Z'),SLOT=21600000,at=c=>new Date(EPOCH+c*SLOT).toISOString();
const dir=t=>{const p=fs.mkdtempSync(path.join(os.tmpdir(),'factory-late-cross-'));
 t.after(()=>fs.rmSync(p,{recursive:true,force:true}));return p;};
test('unbuilt earlier slots after a later accepted candidate get oldest-first tested packages, not fake historical success',t=>{
 if(process.platform==='win32')return t.skip('Linux executed lifecycle mandatory');
 const root=dir(t),current=runCrossCycle({at:at(8),outputRoot:root});
 assert.equal(current.accepted,1);assert.equal(current.verifiedSlot.recoveredLate,undefined);
 const plan=planCrossBackfill({at:at(8),outputRoot:root});
 assert.equal(plan.unbuiltHistoricalSlots,8);
 assert.deepEqual(plan.nextEligibleSlots,[0,1]);
 assert.equal(plan.historicalRunsNotEstablished,true);
 const result=runCrossBackfill({at:at(8),outputRoot:root});
 assert.equal(result.verifiedLateBuilds,2);
 assert.deepEqual(result.lateBuiltSlots.map(x=>x.cycle),[0,1]);
 assert.equal(result.remainingUnbuiltHistoricalSlots,6);
 assert.equal(result.moreDue,true);assert.equal(result.originalScheduledRunProof,false);
 assert.equal(result.externalContacts,0);assert.equal(result.realCustomers,null);
 assert.equal(result.collectedRevenue,null);assert.equal(result.releaseApproved,false);
 for(const recovered of result.lateBuiltSlots){
  assert.equal(recovered.lateBuilt,true);
  assert.ok(Date.parse(recovered.executedAt)>=EPOCH+(recovered.cycle+1)*SLOT);
  assert.notEqual(recovered.key,current.selected.key);
 }
 const entries=readJournal(root,loadOpportunities());
 assert.equal(entries.length,3);
 assert.equal(entries.find(x=>x.cycle===8).key,current.selected.key);
 for(const entry of entries.filter(x=>x.cycle<8))assert.equal(entry.recoveredLate,true);
 assert.throws(()=>runCrossCycle({at:at(2),outputRoot:root}),/CROSS_FUTURE_RECEIPT/);
 const next=runCrossBackfill({at:at(8),outputRoot:root});
 assert.deepEqual(next.lateBuiltSlots.map(x=>x.cycle),[2,3]);
 assert.equal(next.remainingUnbuiltHistoricalSlots,4);
 assert.equal(new Set(readJournal(root,loadOpportunities()).map(x=>x.key)).size,5);
});
test('forged past execution time and corrupted package block further history repair',t=>{
 if(process.platform==='win32')return t.skip('Linux executed lifecycle mandatory');
 const root=dir(t);runCrossCycle({at:at(8),outputRoot:root});
 runCrossBackfill({at:at(8),outputRoot:root,maxBuilds:1});
 const filename=path.join(root,'receipts','cycle-0.json'),original=fs.readFileSync(filename);
 const tampered=JSON.parse(original);
 tampered.executedAt='2026-10-13T00:01:00Z';
 tampered.digest=crypto.createHash('sha256').update(JSON.stringify({...tampered,digest:undefined})).digest('hex');
 fs.writeFileSync(filename,JSON.stringify(tampered)+'\n');
 assert.throws(()=>runCrossBackfill({at:at(8),outputRoot:root}),/CROSS_RECEIPT_INVALID/);
 assert.equal(fs.existsSync(path.join(root,'receipts','cycle-1.json')),false);
 fs.writeFileSync(filename,original);
 const pkg=path.join(root,'packages','cycle-0',tampered.key+'-'+tampered.packageDigest);
 fs.appendFileSync(path.join(pkg,'manifest.json'),'tampered');
 assert.throws(()=>planCrossBackfill({at:at(8),outputRoot:root}),/CROSS_EVIDENCE_INVALID/);
});
test('bounded lookback never duplicates the current cycle or silently certifies earlier history outside its window',t=>{
 if(process.platform==='win32')return t.skip('Linux executed lifecycle mandatory');
 const root=dir(t);runCrossCycle({at:at(8),outputRoot:root});
 const first=runCrossBackfill({at:at(8),outputRoot:root,maxBuilds:1,windowCycles:2});
 assert.equal(first.verifiedLateBuilds,1);assert.equal(first.lateBuiltSlots[0].cycle,6);
 assert.equal(first.historyOutsideWindowUnverified,true);
 assert.equal(first.remainingUnbuiltHistoricalSlots,1);
 const second=runCrossBackfill({at:at(8),outputRoot:root,maxBuilds:1,windowCycles:2});
 assert.equal(second.lateBuiltSlots[0].cycle,7);
 const last=runCrossBackfill({at:at(8),outputRoot:root,maxBuilds:1,windowCycles:2});
 assert.equal(last.verifiedLateBuilds,0);assert.equal(last.moreDue,false);
 assert.equal(readJournal(root,loadOpportunities()).length,3);
});
test('unsafe clock, unbounded lookback, duplicate work and all contact flags fail closed',t=>{
 const root=dir(t);
 assert.throws(()=>main(['--run','--output','relative']),/USAGE_INVALID/);
 assert.throws(()=>main(['--run','--output',root,'--max-builds','9']),/USAGE_INVALID/);
 assert.throws(()=>main(['--run','--output',root,'--window-cycles','999']),/USAGE_INVALID/);
 assert.throws(()=>main(['--run','--output',root,'--send-email','yes']),/USAGE_INVALID/);
 assert.throws(()=>planCrossBackfill({at:'2099-10-13T00:00:00Z',outputRoot:root}),/CROSS_BACKFILL_FUTURE_INVALID/);
 assert.throws(()=>planCrossBackfill({at:'not-date',outputRoot:root}),/CROSS_TIME_INVALID/);
 const lock=path.join(root,'.cross-backfill.lock');
 fs.writeFileSync(lock,'busy',{mode:0o600});
 assert.throws(()=>runCrossBackfill({at:at(8),outputRoot:root}),/CROSS_BACKFILL_BUSY/);
 fs.unlinkSync(lock);
 const planned=main(['--plan','--output',root,'--at',at(8)]);
 assert.equal(planned.historicalRunsNotEstablished,true);
 assert.equal(planned.transmittedMessages,0);
 assert.equal(planned.paymentsSent,0);
 assert.equal(planned.releaseApproved,false);
});
